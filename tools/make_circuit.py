"""Builds backend/src/games/apex/circuit.ts: the Apex Circuit lap (a closed spline through 12 points, scaled x1.3, sampled about every 8 m).
Run: python3 tools/make_circuit.py   then   node scripts/sync-apex.mjs"""
import numpy as np, os
from scipy.interpolate import splprep, splev
base = np.array([[0,-200],[150,-210],[260,-130],[280,0],[200,90],[80,70],[20,150],[-90,230],[-230,200],[-290,80],[-240,-60],[-130,-120]], float)
pts = np.vstack([base, base[:1]]); tck, u = splprep([pts[:,0], pts[:,1]], s=0, per=True)
x, y = splev(np.linspace(0, 1, 40000), tck)
s = np.concatenate([[0], np.cumsum(np.hypot(np.diff(x), np.diff(y)))]); L0 = s[-1]
SC = 1.3; L = L0 * SC; n = int(round(L / 8)); step = L / n
ss = np.linspace(0, L0, n, endpoint=False); xs = np.interp(ss, s, x) * SC; ys = np.interp(ss, s, y) * SC
th = np.unwrap(np.arctan2(np.gradient(xs), -np.gradient(ys)))
k = np.gradient(th) / step
k = np.convolve(np.r_[k[-3:], k, k[:3]], np.ones(7) / 7, 'valid')
low = (np.abs(k) < 0.0025).astype(int); best = (0, 0)
for i in range(n):
    c = 0
    while c < n and low[(i + c) % n]: c += 1
    if c > best[1]: best = (i, c)
st = (best[0] + best[1] // 2) % n  # start in the middle of the straightest stretch
xs = np.roll(xs, -st); ys = np.roll(ys, -st); k = np.roll(k, -st)
r = lambda a, d: '[' + ','.join(('%.*f' % (d, v)).rstrip('0').rstrip('.') for v in a) + ']'
src = f"""// Generated by tools/make_circuit.py: one closed lap, sampled every {step:.4f} m. x/z are the road centre in the 3D scene, k is 1 / radius (+ turns right).
// The race rules read only `k`; the phone draws the road from `x` and `z`. Do not edit by hand.
export const CIRCUIT = {{
  length: {L:.3f},
  step: {step:.5f},
  x: {r(xs,1)},
  z: {r(ys,1)},
  k: {r(k,5)},
}};
"""
open(os.path.join(os.path.dirname(__file__), '..', 'backend', 'src', 'games', 'apex', 'circuit.ts'), 'w').write(src)
print('lap', L, 'm, min radius', 1 / np.abs(k).max(), 'm')
